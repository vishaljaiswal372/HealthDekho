-- HealthDekho current-scope schema (spec section 5.2, FR-1 .. FR-5).
-- Money: NUMERIC(19,2). Dates: DATE. Audit timestamps: TIMESTAMP WITH TIME ZONE.
-- Claim tables (FE-1) are future scope and intentionally not created here.

-- ---------------------------------------------------------------------------
-- customer: authenticated customer profile
-- ---------------------------------------------------------------------------
CREATE TABLE customer (
    customer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(150) NOT NULL,
    date_of_birth   DATE         NOT NULL,
    phone           VARCHAR(20),
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT ck_customer_dob_not_future CHECK (date_of_birth <= CURRENT_DATE),
    CONSTRAINT ck_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);
CREATE INDEX ix_customer_status ON customer (status);
CREATE INDEX ix_customer_full_name_lower ON customer (lower(full_name));

-- ---------------------------------------------------------------------------
-- insurance_product: master catalog (kept separate from customer transactions)
-- ---------------------------------------------------------------------------
CREATE TABLE insurance_product (
    product_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code        VARCHAR(30)    NOT NULL,
    policy_name         VARCHAR(150)   NOT NULL,
    policy_type         VARCHAR(20)    NOT NULL,
    term_months         INTEGER        NOT NULL,
    premium_frequency   VARCHAR(20)    NOT NULL,
    premium_amount      NUMERIC(19, 2) NOT NULL,
    sum_insured         NUMERIC(19, 2) NOT NULL,
    min_entry_age       INTEGER        NOT NULL,
    max_entry_age       INTEGER        NOT NULL,
    active              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_product_code UNIQUE (product_code),
    CONSTRAINT ck_product_type CHECK (policy_type IN ('TERM', 'HEALTH', 'SAVINGS', 'LIFE')),
    CONSTRAINT ck_product_frequency CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_product_term_positive CHECK (term_months > 0),
    CONSTRAINT ck_product_premium_positive CHECK (premium_amount > 0),
    CONSTRAINT ck_product_sum_insured_positive CHECK (sum_insured > 0),
    CONSTRAINT ck_product_entry_age CHECK (min_entry_age >= 0 AND max_entry_age >= min_entry_age),
    -- term must divide evenly into the premium frequency's period length
    CONSTRAINT ck_product_term_matches_frequency CHECK (
        term_months % CASE premium_frequency
                         WHEN 'MONTHLY' THEN 1
                         WHEN 'QUARTERLY' THEN 3
                         WHEN 'HALF_YEARLY' THEN 6
                         WHEN 'YEARLY' THEN 12
                      END = 0)
);
CREATE INDEX ix_product_active ON insurance_product (active);
CREATE INDEX ix_product_type ON insurance_product (policy_type);

-- ---------------------------------------------------------------------------
-- customer_policy: a policy registered by a customer.
-- Product terms are copied at registration so later catalog edits don't
-- rewrite existing contracts.
-- ---------------------------------------------------------------------------
CREATE TABLE customer_policy (
    policy_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number       VARCHAR(30)    NOT NULL,
    customer_id         BIGINT         NOT NULL REFERENCES customer (customer_id),
    product_id          BIGINT         NOT NULL REFERENCES insurance_product (product_id),
    term_months         INTEGER        NOT NULL,
    start_date          DATE           NOT NULL,
    maturity_date       DATE           NOT NULL,
    premium_frequency   VARCHAR(20)    NOT NULL,
    premium_amount      NUMERIC(19, 2) NOT NULL,
    sum_insured         NUMERIC(19, 2) NOT NULL,
    total_premium       NUMERIC(19, 2) NOT NULL,
    status              VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_policy_number UNIQUE (policy_number),
    -- duplicate-registration rule: one policy per customer per product
    CONSTRAINT uq_policy_customer_product UNIQUE (customer_id, product_id),
    CONSTRAINT ck_policy_dates CHECK (maturity_date > start_date),
    CONSTRAINT ck_policy_term_positive CHECK (term_months > 0),
    CONSTRAINT ck_policy_premium_positive CHECK (premium_amount > 0),
    CONSTRAINT ck_policy_sum_insured_positive CHECK (sum_insured > 0),
    CONSTRAINT ck_policy_total_premium_positive CHECK (total_premium > 0),
    CONSTRAINT ck_policy_frequency CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_policy_status CHECK (status IN ('ACTIVE', 'FULLY_PAID', 'MATURED', 'CANCELLED'))
);
CREATE INDEX ix_policy_customer ON customer_policy (customer_id);
CREATE INDEX ix_policy_product ON customer_policy (product_id);

-- ---------------------------------------------------------------------------
-- premium_installment: the payment schedule of a policy
-- ---------------------------------------------------------------------------
CREATE TABLE premium_installment (
    installment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id           BIGINT         NOT NULL REFERENCES customer_policy (policy_id),
    installment_no      INTEGER        NOT NULL,
    due_date            DATE           NOT NULL,
    grace_end_date      DATE           NOT NULL,
    scheduled_amount    NUMERIC(19, 2) NOT NULL,
    penalty_amount      NUMERIC(19, 2) NOT NULL DEFAULT 0,
    paid_amount         NUMERIC(19, 2) NOT NULL DEFAULT 0,
    payment_status      VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_installment_policy_no UNIQUE (policy_id, installment_no),
    CONSTRAINT ck_installment_no_positive CHECK (installment_no > 0),
    CONSTRAINT ck_installment_grace CHECK (grace_end_date >= due_date),
    CONSTRAINT ck_installment_scheduled_positive CHECK (scheduled_amount > 0),
    CONSTRAINT ck_installment_penalty_non_negative CHECK (penalty_amount >= 0),
    -- never more than the scheduled amount plus any applicable penalty
    CONSTRAINT ck_installment_paid_range CHECK (paid_amount >= 0 AND paid_amount <= scheduled_amount + penalty_amount),
    CONSTRAINT ck_installment_status CHECK (payment_status IN ('PAID', 'PENDING', 'PARTIALLY_PAID', 'OVERDUE'))
);
CREATE INDEX ix_installment_policy ON premium_installment (policy_id);
CREATE INDEX ix_installment_due_status ON premium_installment (due_date, payment_status);

-- ---------------------------------------------------------------------------
-- premium_payment: immutable payment transaction history
-- ---------------------------------------------------------------------------
CREATE TABLE premium_payment (
    payment_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id          BIGINT         NOT NULL REFERENCES premium_installment (installment_id),
    transaction_reference   VARCHAR(40)    NOT NULL,
    payment_date            DATE           NOT NULL,
    amount_paid             NUMERIC(19, 2) NOT NULL,
    penalty_amount          NUMERIC(19, 2) NOT NULL DEFAULT 0,
    payment_method          VARCHAR(20)    NOT NULL,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_payment_txn_ref UNIQUE (transaction_reference),
    CONSTRAINT ck_payment_amount_positive CHECK (amount_paid > 0),
    CONSTRAINT ck_payment_penalty_non_negative CHECK (penalty_amount >= 0),
    CONSTRAINT ck_payment_method CHECK (payment_method IN ('UPI', 'NET_BANKING', 'CARD', 'CASH', 'CHEQUE'))
);
CREATE INDEX ix_payment_installment_date ON premium_payment (installment_id, payment_date);

-- Payment rows are an audit trail: reject UPDATE and DELETE at the database level.
CREATE FUNCTION premium_payment_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'premium_payment rows are immutable (% blocked)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_premium_payment_immutable
    BEFORE UPDATE OR DELETE ON premium_payment
    FOR EACH ROW EXECUTE FUNCTION premium_payment_immutable();

-- ---------------------------------------------------------------------------
-- ai_recommendation_request: one row per recommendation interaction
-- ---------------------------------------------------------------------------
CREATE TABLE ai_recommendation_request (
    recommendation_request_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id                 BIGINT       NOT NULL REFERENCES customer (customer_id),
    insurance_goals             TEXT,
    preferred_term_months       INTEGER,
    preferred_policy_type       VARCHAR(20),
    calculated_age              INTEGER      NOT NULL,
    model_name                  VARCHAR(100) NOT NULL,
    model_version               VARCHAR(100),
    prompt_version              VARCHAR(50)  NOT NULL,
    requested_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_rec_req_term_positive CHECK (preferred_term_months IS NULL OR preferred_term_months > 0),
    CONSTRAINT ck_rec_req_age CHECK (calculated_age >= 0),
    CONSTRAINT ck_rec_req_type CHECK (preferred_policy_type IS NULL OR preferred_policy_type IN ('TERM', 'HEALTH', 'SAVINGS', 'LIFE'))
);
CREATE INDEX ix_rec_req_customer_requested ON ai_recommendation_request (customer_id, requested_at);

-- ---------------------------------------------------------------------------
-- ai_recommendation_item: products returned for a recommendation request
-- ---------------------------------------------------------------------------
CREATE TABLE ai_recommendation_item (
    recommendation_item_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_request_id   BIGINT      NOT NULL REFERENCES ai_recommendation_request (recommendation_request_id),
    product_id                  BIGINT      NOT NULL REFERENCES insurance_product (product_id),
    rank_order                  INTEGER     NOT NULL,
    recommendation_reason       TEXT        NOT NULL,
    suitability                 VARCHAR(10) NOT NULL,
    selected_for_registration   BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_rec_item_request_product UNIQUE (recommendation_request_id, product_id),
    CONSTRAINT ck_rec_item_rank_positive CHECK (rank_order > 0),
    CONSTRAINT ck_rec_item_suitability CHECK (suitability IN ('HIGH', 'MEDIUM', 'LOW'))
);
CREATE INDEX ix_rec_item_product ON ai_recommendation_item (product_id);
